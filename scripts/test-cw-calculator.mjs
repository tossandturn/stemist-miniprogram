import assert from 'node:assert/strict'
import fs from 'node:fs'
import { miniRuntime } from './helpers/mini-runtime.mjs'
const engine = miniRuntime().load('utils/calculator')
let count = 0
function test(name, run) { run(); console.log('PASS ' + name); count++ }
function close(actual, expected, tolerance=1e-11) { assert.ok(Math.abs(actual-expected) <= tolerance, `${actual} != ${expected}`) }

test('CW fraction, base logarithm, roots and combinatorics evaluate locally', () => {
  close(engine.evaluateExpression('frac(1,2)+frac(1,3)'), 5/6)
  close(engine.evaluateExpression('logb(2,32)'), 5)
  close(engine.evaluateExpression('root(3,-8)'), -2)
  assert.equal(engine.evaluateExpression('ncr(10,3)'),120)
  assert.equal(engine.evaluateExpression('npr(10,3)'),720)
  assert.throws(()=>engine.evaluateExpression('frac(1,0)'))
  assert.throws(()=>engine.evaluateExpression('ncr(2,5)'))
})
test('CW angle settings include gradians and preserve constant e versus variable E', () => {
  close(engine.evaluateExpression('sin(100)',{angleMode:'GRAD'}),1)
  close(engine.evaluateExpression('E+e',{variables:{E:5}}),5+Math.E)
  close(engine.evaluateExpression('2x+3A',{variables:{x:4,A:2}}),14)
})
test('stored functions have bounded recursion and variable scope', () => {
  close(engine.evaluateExpression('f(3)+g(2)',{functions:{f:'x^2',g:'x+1'}}),12)
  assert.throws(()=>engine.evaluateExpression('f(1)',{functions:{f:'f(x)'}}),/递归|层数/)
  assert.throws(()=>engine.evaluateExpression('globalThis.process.exit()'))
})
