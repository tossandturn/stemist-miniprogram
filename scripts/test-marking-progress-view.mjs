import assert from 'node:assert/strict'
import {miniRuntime} from './helpers/mini-runtime.mjs'
const {markingProgress}=miniRuntime().load('bundles/marking/progress')
const view=(status,stage,progress={})=>markingProgress({status,progress:{stage,...progress}})
assert.equal(view('queued','queued').etaLabel,'正在排队')
assert.equal(view('queued','queued',{isEstimate:true,estimatedRemainingSeconds:12,estimateScope:'processing-only'}).etaLabel,'正在排队','queue time is never invented from processing estimates')
const preparing=view('processing','rendering-answer-pages',{label:'Rendering answer pages',completedPages:3,totalPages:8,elapsedSeconds:14})
assert.equal(preparing.label,'准备作答中')
assert.equal(preparing.pagePercent,37)
assert.equal(preparing.preparing,true)
assert.equal(preparing.elapsedLabel,'已用时 14 秒')
assert.equal(preparing.pageLabel,'已准备 3 / 8 页')
const ai=view('processing','ai-review',{label:'provider debug text',completedPages:8,totalPages:8})
assert.equal(ai.label,'分析作答中')
assert.equal(ai.preparing,false,'prepared file pages do not imply AI percent complete')
assert.equal(ai.pagePercent,null,'AI analysis never turns prepared-page count into a fake completion percent')
assert.equal(ai.pageLabel,'已提交 8 / 8 页进行分析')
assert.equal(ai.etaLabel,'暂没有可靠的预计完成时间')
assert.equal(ai.etaSourceLabel,'')
assert.equal(view('processing','reporting').label,'整理报告中')
assert.equal(view('processing','ai-review',{isEstimate:true,estimatedRemainingSeconds:15,estimateScope:'processing-only'}).etaLabel,'预计还需约 15 秒')
assert.equal(view('processing','ai-review',{isEstimate:true,estimatedRemainingSeconds:15,estimateScope:'processing-only'}).etaSourceLabel,'根据历史任务耗时与页数估算')
assert.equal(view('processing','ai-review',{isEstimate:true,estimatedRemainingSeconds:0,estimateScope:'processing-only'}).etaLabel,'暂没有可靠的预计完成时间')
assert.equal(view('processing','ai-review',{completedPages:9,totalPages:8}).pagePercent,null)
assert.equal(view('completed','completed').active,false)
const failed=view('failed','failed',{elapsedSeconds:65})
assert.equal(failed.active,false)
assert.equal(failed.terminal,true)
assert.equal(failed.elapsedLabel,'总耗时 1 分 5 秒')
const diagnosed=view('failed','failed',{lastStage:'reporting',phaseElapsed:7,elapsedSeconds:65})
assert.equal(diagnosed.phaseLabel,'整理报告中')
assert.equal(diagnosed.phaseElapsedLabel,'失败前阶段用时 7 秒')
console.log('Marking view: translated real stages, actual page progress, bounded estimates, queue and unknown states passed.')
