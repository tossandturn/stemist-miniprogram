import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const app = JSON.parse(read('app.json'))

function handlerNames(wxml) {
  const names = new Set()
  const pattern = /\bbind(?::|)(?:tap|input|change|confirm|load|error|scale|action|submit|retry|account|clear)\s*=\s*"([A-Za-z_$][\w$]*)"/g
  for (const match of wxml.matchAll(pattern)) names.add(match[1])
  return [...names]
}

for (const page of app.pages) {
  const wxml = read(`${page}.wxml`)
  const source = read(`${page}.js`)
  // Listening/Reading are generated by makeTextSkillPage; the factory has a
  // single tested implementation, so its handlers are checked separately.
  if (!/makeTextSkillPage\s*\(/.test(source)) {
    for (const name of handlerNames(wxml)) {
      assert.match(source, new RegExp(`(?:${name}\\s*\\(|${name}\\s*:)`), `${page} references missing handler ${name}`)
    }
  }
  for (const match of wxml.matchAll(/\burl="(\/pages\/[^"?]+)(?:\?[^" ]*)?"/g)) {
    const target = match[1].replace(/^\//, '').replace(/\/$/, '')
    assert.ok(app.pages.includes(target), `${page} points to an unregistered page ${target}`)
  }
}

console.log(`WXML handler and internal page-link contract passed for ${app.pages.length} pages.`)
