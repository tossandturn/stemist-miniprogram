import assert from 'node:assert/strict'
import {miniRuntime} from './helpers/mini-runtime.mjs'
const rt=miniRuntime(),s=rt.load('utils/coachEffort')
assert.equal(s.readCoachEffort('tavern'),'low')
assert.equal(s.readCoachEffort('steps'),'low')
assert.equal(s.readCoachEffort('answers'),'low')
assert.equal(s.readCoachEffort('check'),'low')
assert.equal(s.readCoachEffort('pdf'),'high')
assert.equal(s.readCoachEffort('admissions'),'low')
assert.equal(s.readCoachEffort('admissions','帮我分析申请竞争力并制定选校规划'),'high')
assert.equal(s.readCoachEffort('ielts-teacher','你好，口语 Part 1 练一题'),'low')
assert.equal(s.readCoachEffort('ielts-teacher','请逐段修改这篇作文'),'high')
s.saveCoachEffort('max','answers');assert.equal(s.readCoachEffort('answers'),'max');assert.equal(s.readCoachEffort('tavern'),'low')
s.saveCoachEffort('low','admissions');assert.equal(s.readCoachEffort('admissions','请分析申请竞争力'),'low','manual choice wins over intent')
s.saveCoachEffort('auto','admissions');assert.equal(s.readCoachEffort('admissions','请分析申请竞争力'),'high')
assert.equal(s.coachEffortPreference('admissions'),'auto')
rt.storage.set('stemistUser',{id:'new-owner'});assert.equal(s.readCoachEffort('answers'),'low')
rt.storage.set('stemistPrivacyEpoch',4);s.saveCoachEffort('low','answers');rt.storage.set('stemistPrivacyEpoch',5);assert.equal(s.readCoachEffort('answers'),'low')
assert.equal(s.academicEffortScope('hint','answers'),'steps');assert.equal(s.academicEffortScope('check-work','answers'),'check');assert.equal(s.academicEffortScope('','answers'),'answers')
for(const scope of ['steps','answers','check','pdf','tavern','admissions','ielts-teacher'])assert.notEqual(s.readCoachEffort(scope,'A'.repeat(1500)),'max','max is always opt-in')
assert.throws(()=>s.saveCoachEffort('max','unknown-scope'))
console.log('Scenario effort: independent defaults, local intent, explicit override, reset, privacy and max opt-in PASS.')
