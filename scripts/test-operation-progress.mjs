import assert from 'node:assert/strict'
import {miniRuntime} from './helpers/mini-runtime.mjs'
const r=miniRuntime(),module=r.load('utils/operationProgress')
let time=0,id=0;const timers=new Map(),states=[]
const tracker=module.createOperationTracker({key:'coach-photo',onChange:s=>states.push(s),now:()=>time,setTimer:f=>{timers.set(++id,f);return id},clearTimer:i=>timers.delete(i),history:r.wx})
assert.equal(states.at(-1).phase,'preparing')
assert.equal(states.at(-1).etaLabel,'预计时间估算中')
tracker.stage('calling');tracker.stage('analysis');tracker.stage('calling')
assert.equal(states.at(-1).phase,'analysis','late stage cannot move a newer phase backwards')
time=4000;timers.values().next().value()
assert.match(states.at(-1).elapsedLabel,/4 秒/)
assert.equal(states.at(-1).percentage,null,'a waiting model must not receive timer-based percentage')
tracker.stage('arranging');tracker.finish(true)
assert.equal(states.at(-1).phase,'complete')
assert.equal(timers.size,0)
const recorded=r.storage.get('stemistOperationTimings');assert.equal(recorded.items[0].ms,4000)
assert.deepEqual(Object.keys(recorded.items[0]).sort(),['at','key','ms'])
tracker.stage('analysis');assert.equal(states.at(-1).phase,'complete')
const samples={schema:'operation-timing-v1',items:[10000,12000,18000].map((ms,i)=>({key:'coach-photo',ms,at:100000-i}))}
r.storage.set('stemistOperationTimings',samples)
time=200000
const estimated=module.createOperationTracker({key:'coach-photo',now:()=>time,onChange:s=>states.push(s),setTimer:()=>1,clearTimer(){},history:r.wx})
assert.match(states.at(-1).etaLabel,/预计/)
time+=100000;estimated.stage('analysis')
assert.equal(states.at(-1).etaSeconds,null)
assert.match(states.at(-1).etaLabel,/仍在处理/)
const before=r.storage.get('stemistOperationTimings').items.length;estimated.finish(false)
assert.equal(r.storage.get('stemistOperationTimings').items.length,before,'failed calls are not successful timing samples')
assert.equal(states.at(-1).phase,'failed')
time=500000;r.storage.set('stemistOperationTimings',{schema:'operation-timing-v1',items:[{key:'coach-photo',ms:4000,at:time,content:'synthetic private text',owner:'synthetic-owner'}]})
const sanitized=module.createOperationTracker({key:'coach-photo',now:()=>time,setTimer:()=>1,clearTimer(){},history:r.wx})
time+=2000;sanitized.finish(true)
assert(r.storage.get('stemistOperationTimings').items.every(item=>Object.keys(item).sort().join(',')==='at,key,ms'),'only numeric timings are retained, including imported historical records')
console.log('Operation progress: real lifecycle phases, elapsed time, no synthetic percentage, measured estimates, timeout/terminal and numeric-only history passed.')
