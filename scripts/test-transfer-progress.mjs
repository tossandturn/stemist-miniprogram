import assert from 'node:assert/strict'
import fs from 'node:fs'
import {miniRuntime} from './helpers/mini-runtime.mjs'
const {buildTransferProgress:build}=miniRuntime().load('utils/transferProgress')
const start=build({},'试卷')
assert.equal(start.visible,true)
assert.equal(start.phase,'connecting')
assert.equal(start.active,true)
assert.equal(start.knownTotal,false)
assert.equal(start.percent,null)
assert.match(start.message,/连接/)
const half=build({downloaded:512,total:1024,phase:'downloading',speedLabel:'1 KB/s',remainingLabel:'约 1 秒'},'报告')
assert.equal(half.percent,50)
assert.equal(half.downloadedLabel,'512 B')
assert.equal(half.totalLabel,'1.0 KB')
assert.equal(half.speedLabel,'1 KB/s')
for(const phase of ['downloading','verifying','opening'])assert.equal(build({downloadedBytes:1024,totalBytes:1024,phase}).percent,99,'pending verification/open is not complete')
assert.equal(build({downloadedBytes:1024,totalBytes:1024,phase:'ready'}).percent,100)
assert.equal(build({downloadedBytes:1024,totalBytes:1024,phase:'opening',complete:true}).percent,100,'verified cache/opening does not regress from 100')
assert.equal(build({phase:'cached',fromCache:true}).percent,null,'unknown cache size is not invented')
assert.equal(build({phase:'ready'}).downloadedLabel,'','completed file with unavailable size does not claim a zero-byte file')
assert.match(build({phase:'cached',fromCache:true}).message,/缓存/)
for(const phase of ['ready','cached','paused','error'])assert.equal(build({phase}).active,false)
const paused=build({...half,phase:'paused'},'报告',{canRetry:true,error:'',canCancel:false})
assert.equal(paused.percent,50)
assert.equal(paused.speedLabel,'','stale throughput is not shown while paused')
assert.equal(paused.remainingLabel,'')
assert.equal(paused.canRetry,true)
const unknown=build({downloadedBytes:512,totalBytes:Infinity,phase:'downloading'})
assert.equal(unknown.knownTotal,false)
assert.equal(unknown.percent,null)
assert.equal(unknown.downloadedLabel,'512 B')
assert.equal(build({downloadedBytes:-1,totalBytes:-1}).downloadedBytes,0)
assert.equal(build({downloadedBytes:NaN,totalBytes:NaN}).percent,null)
assert.equal(build({downloaded:20,total:100},{},{percent:100,knownTotal:false}).percent,20,'overrides cannot forge byte-derived progress')
const wxml=fs.readFileSync(new URL('../components/pdf-download-progress/index.wxml',import.meta.url),'utf8')
assert.match(wxml,/is-indeterminate/,'unknown active size has a visible nonnumeric bar')
assert.match(wxml,/!compact/,'inline panels need no nonworking collapse control')
const css=fs.readFileSync(new URL('../components/pdf-download-progress/index.wxss',import.meta.url),'utf8')
assert.match(css,/prefers-reduced-motion[\s\S]*animation:none/)
console.log('Transfer progress: measured bytes, unknown sizes, completion, cache, pause and accessible indeterminate panel passed.')
